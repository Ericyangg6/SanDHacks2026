// Builds alerts/zone-zips.ts, the table that turns the NWS forecast zones an alert names into zip codes:
//   node src/m4/dev/run.mjs build-zone-zips <path to <year>_Gaz_zcta_national.txt>
// Run from apps/api. Get the file from the Census Gazetteer (ZIP Code Tabulation Areas, national, unzip it):
//   https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2025_Gazetteer/2025_Gaz_zcta_national.zip
// A zip belongs to the zone whose polygon (from api.weather.gov) contains the zip area's internal point.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { env } from '../env';
import { SD_COUNTY_ZONES } from '../alerts/zones';

type Ring = [number, number][]; // [lon, lat]
type Polygon = Ring[]; // outer ring, then holes

const OUT = path.join('src', 'm4', 'alerts', 'zone-zips.ts');

const gazetteer = process.argv[3];
if (!gazetteer || !existsSync(gazetteer)) throw new Error('Usage: build-zone-zips <path to *_Gaz_zcta_national.txt>');
if (!existsSync(path.dirname(OUT))) throw new Error('Run this from apps/api');

// Ray casting on one ring.
function inRing(lon: number, lat: number, ring: Ring): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function inPolygon(lon: number, lat: number, polygon: Polygon): boolean {
  return inRing(lon, lat, polygon[0]) && !polygon.slice(1).some((hole) => inRing(lon, lat, hole));
}

async function zonePolygons(code: string): Promise<{ polygons: Polygon[]; effective: string }> {
  const response = await fetch(`https://api.weather.gov/zones/forecast/${code}`, {
    headers: { 'User-Agent': env.nwsUserAgent(), Accept: 'application/geo+json' },
  });
  if (!response.ok) throw new Error(`NWS zone ${code}: HTTP ${response.status}`);
  const zone = (await response.json()) as {
    geometry: { type: 'Polygon'; coordinates: Polygon } | { type: 'MultiPolygon'; coordinates: Polygon[] } | null;
    properties: { effectiveDate?: string };
  };
  if (!zone.geometry) throw new Error(`NWS zone ${code} has no geometry`);
  const polygons = zone.geometry.type === 'Polygon' ? [zone.geometry.coordinates] : zone.geometry.coordinates;
  return { polygons, effective: zone.properties.effectiveDate ?? 'unknown' };
}

const zones = await Promise.all(SD_COUNTY_ZONES.map(async (z) => ({ ...z, ...(await zonePolygons(z.code)) })));

// GEOID|GEOIDFQ|ALAND|AWATER|ALAND_SQMI|AWATER_SQMI|INTPTLAT|INTPTLONG
const [header, ...rows] = readFileSync(gazetteer, 'utf8').trim().split(/\r?\n/);
const columns = header.split('|').map((c) => c.trim());
const [zipCol, latCol, lonCol] = ['GEOID', 'INTPTLAT', 'INTPTLONG'].map((name) => columns.indexOf(name));
if ([zipCol, latCol, lonCol].includes(-1)) throw new Error(`Unexpected gazetteer columns: ${header}`);

const table: Record<string, string[]> = Object.fromEntries(SD_COUNTY_ZONES.map((z) => [z.code, []]));
for (const row of rows) {
  const cells = row.split('|').map((c) => c.trim());
  const zip = cells[zipCol];
  const lat = Number(cells[latCol]);
  const lon = Number(cells[lonCol]);
  // Cheap box around San Diego County before the polygon test.
  if (!/^\d{5}$/.test(zip) || lat < 32.4 || lat > 33.6 || lon < -117.7 || lon > -115.9) continue;
  const zone = zones.find((z) => z.polygons.some((p) => inPolygon(lon, lat, p)));
  if (zone) table[zone.code].push(zip);
}

const source = path.basename(gazetteer);
const built = new Date().toISOString().slice(0, 10);
const lines = [
  '// Generated by dev/build-zone-zips.ts. Do not edit by hand: rerun it.',
  `// Source: Census Gazetteer ${source} (ZIP Code Tabulation Areas, internal points) and the NWS forecast zone`,
  `// polygons from api.weather.gov (${zones.map((z) => `${z.code} effective ${z.effective.slice(0, 10)}`).join(', ')}).`,
  `// Built ${built}. A zip is in the zone that contains its ZCTA's internal point, so a zip that straddles two zones`,
  '// is listed once. PO-box-only zips have no ZCTA and are missing.',
  '',
  'export const ZONE_ZIPS: Record<string, readonly string[]> = {',
  ...SD_COUNTY_ZONES.map((z) => {
    const zips = table[z.code].sort();
    const chunks: string[] = [];
    for (let i = 0; i < zips.length; i += 10) chunks.push(`    ${zips.slice(i, i + 10).map((zip) => `'${zip}'`).join(', ')},`);
    return [`  // ${z.name}: ${zips.length} zips`, `  ${z.code}: [`, ...chunks, '  ],'].join('\n');
  }),
  '};',
  '',
];
writeFileSync(OUT, lines.join('\n'));

for (const z of SD_COUNTY_ZONES) console.log(`${z.code} ${z.name}: ${table[z.code].length} zips`);
for (const zip of ['92020', '92037', '92105', '92101', '91910', '92004', '92036', '92028']) {
  console.log(`  ${zip} -> ${Object.entries(table).find(([, zips]) => zips.includes(zip))?.[0] ?? 'none'}`);
}
console.log(`Wrote ${OUT}`);
